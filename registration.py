def get_registration_text(uid):
    return _interpolate(uid)

def get_telegram_era(uid):
    uid = abs(int(uid))
    for lo, hi, label in ERAS:
        if lo <= uid <= hi:
            return label
    return "✨ Latest Wave"

def get_full_registration_info(uid):
    uid = abs(int(uid))
    date_str = _interpolate(uid)
    era = get_telegram_era(uid)
    y, m = _parse(date_str)

    now = datetime.now()
    diff_months = (now.year - y) * 12 + now.month - m
    years = diff_months // 12
    months = diff_months % 12

    if years > 0:
        age = f"~{years}y {months}m ago"
    elif months > 0:
        age = f"~{months}m ago"
    else:
        age = "Recent"

    return {
        "date": date_str,
        "formatted": age,
        "year": y,
        "era": era,
    }
