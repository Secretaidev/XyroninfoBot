_IDS = [m[0] for m in MILESTONES]
_DATES = [m[1] for m in MILESTONES]
_MONTH_MAP = {"Jan":1,"Feb":2,"Mar":3,"Apr":4,"May":5,"Jun":6,"Jul":7,"Aug":8,"Sep":9,"Oct":10,"Nov":11,"Dec":12}

def _parse(date_str):
    parts = date_str.split()
    return int(parts[1]), _MONTH_MAP.get(parts[0], 1)

def _to_ts(y, m):
    return y * 12 + m

def _interpolate(uid):
    uid = abs(int(uid))
    if uid <= 0:
        return "Aug 2013"
    if uid >= _IDS[-1]:
        return _DATES[-1]

    pos = bisect.bisect_right(_IDS, uid)
    if pos == 0:
        return _DATES[0]
    if pos >= len(_IDS):
        return _DATES[-1]

    lo_id, hi_id = _IDS[pos - 1], _IDS[pos]
    lo_date, hi_date = _DATES[pos - 1], _DATES[pos]

    if lo_id == hi_id:
        return lo_date

    lo_y, lo_m = _parse(lo_date)
    hi_y, hi_m = _parse(hi_date)
    lo_ts, hi_ts = _to_ts(lo_y, lo_m), _to_ts(hi_y, hi_m)

    ratio = (uid - lo_id) / (hi_id - lo_id)
    result_ts = lo_ts + ratio * (hi_ts - lo_ts)
    result_y = int(result_ts) // 12
    result_m = int(result_ts) % 12
    if result_m == 0:
        result_m = 12
        result_y -= 1

    month_names = {v: k for k, v in _MONTH_MAP.items()}
    return f"{month_names.get(result_m, 'Jan')} {result_y}"

